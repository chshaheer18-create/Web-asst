        stalled = stalled + 1 if probs == last else 0
        if stalled >= 3:
            st.warning("Gemini could not fix these after repeated tries: " + "; ".join(probs) + ". Use 'Apply change' to guide it."); return html
        last, rnd = probs, rnd + 1
        S.status["🧪 Tester"] = f"🟢 round {rnd}: fixing {len(probs)} problem(s)"; show_board()
        try:
            new = clean_html(ask("Fix ALL of these problems in the website below, change nothing else, keep every feature working.\nProblems:\n- " + "\n- ".join(probs) + "\nReturn ONLY the full HTML.\n\n" + html))
            if "</html>" in new.lower(): html = new
        except Exception as e:
            st.warning(f"Gemini paused ({e}). Returning the best version so far."); return html

