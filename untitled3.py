# ---------------- FAISS memory (falls back to a local embedder if Gemini embeddings fail) ----------------
def unit(v):
    n = np.linalg.norm(v, axis=1, keepdims=True); n[n == 0] = 1
    return (v / n).astype("float32")

def local_embed(texts, dim=512):
    out = np.zeros((len(texts), dim), "float32")
    for i, t in enumerate(texts):
        for w in re.findall(r"[a-z0-9]+", t.lower()):
            out[i, int(hashlib.md5(w.encode()).hexdigest(), 16) % dim] += 1
    return unit(out)

class Memory:
    def __init__(self):
        self.index, self.texts, self.mode = None, [], "gemini"
        try: self._g(["test"])
        except Exception: self.mode = "local"
    def _g(self, t):
        r = client.models.embed_content(model="gemini-embedding-001", contents=t)
        return unit(np.array([e.values for e in r.embeddings], "float32"))
    def emb(self, t): return self._g(t) if self.mode == "gemini" else local_embed(t)
    def add(self, texts):
        texts = [t for t in texts if t.strip()]
        if not texts: return
        v = self.emb(texts)
        if self.index is None: self.index = faiss.IndexFlatIP(v.shape[1])
        self.index.add(v); self.texts += texts
    def search(self, q, k=5):
        if self.index is None: return []
        _, ids = self.index.search(self.emb([q]), min(k, len(self.texts)))
        return [self.texts[i] for i in ids[0] if i >= 0]

